// Параметры защиты доступа (мастер-код, PIN). Все числа — здесь; пометка у
// каждого: ЗАДАНО (владельцем) или НЕ ИЗМЕРЕНО (оценка, подлежит пересмотру).
class SecurityLimits {
  SecurityLimits._();

  // Длина PIN. ЗАДАНО (формат сервисного PIN).
  static const int pinLength = 4;

  // Длина мастер-кода, цифр. ЗАДАНО владельцем (R2.0, 8 цифр).
  static const int masterCodeDigits = 8;

  // Попытки и блокировка — общие для PIN и мастер-кода. ЗАДАНО владельцем:
  // 3 попытки, 20 минут (SecurityService.maxAttempts / lockoutMinutes).

  // Длина индивидуальной соли, байт. НЕ ИЗМЕРЕНО (16 байт — обычная норма).
  static const int masterSaltBytes = 16;

  // Растяжение хэша мастер-кода: PBKDF2-HMAC-SHA256, число итераций. Сам
  // код — 8 цифр (10^8 вариантов), простой SHA-256 перебирался бы за
  // секунды при утечке хранилища; итерации удорожают перебор. Число
  // подобрано так, чтобы проверка на планшете занимала порядка сотни
  // миллисекунд. НЕ ИЗМЕРЕНО на целевом планшете, подлежит пересмотру.
  static const int masterKdfIterations = 10000;
}

// ------------------------------------------------------------
// УСТРОЙСТВА НА ШИНЕ — адреса ПОДТВЕРЖДЕНЫ 27.09.2026.
//
// Признак "установлено" НЕ дублируется отдельным списком — берётся прямо
// из AppConfig (см. isInstalled). Монетоприёмник и терминал оплаты не
// входят сюда: у них нет отдельного адреса на шине, это входы (DI) того
// же модуля ввода-вывода — см. IoModule ниже.
// ------------------------------------------------------------
enum BusDevice {
  thermo(address: 1, label: 'Термопарный модуль HLS-KWL-4TC'),
  dio(address: 5, label: 'Модуль ввода-вывода CWT-BK-1616'),
  // Адрес 3, не 6: так в коде согласованно с обеих сторон (Kotlin
  // SLAVE_ENERGY и Dart-зеркало в сканере) на 27.09.2026 — счётчик ещё не
  // установлен физически, поэтому адрес не перепроверить измерением;
  // решение оператора — считать верным то, что уже в коде, а не число
  // из черновика задания.
  energyMeter(address: 3, label: 'Счётчик энергии Chint DDSU666');

  const BusDevice({required this.address, required this.label});

  final int address;
  final String label;

  bool isInstalled(AppConfig config) {
    switch (this) {
      case BusDevice.thermo:
        return config.thermoInstalled;
      case BusDevice.dio:
        return config.dioInstalled;
      case BusDevice.energyMeter:
        return config.energyMeterInstalled;
    }
  }
}


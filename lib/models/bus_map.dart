// МОДУЛЬ ВВОДА-ВЫВОДА (адрес BusDevice.dio) — выходы (DO).
//
// Клеммы модуля нумеруются с единицы, смещения Modbus — с нуля.
// ПОДТВЕРЖДЕНО мультиметром 27.09.2026 для насосов 1-4/компрессора/ТЭНа.
// Насосы 5-8 — ПЛАНИРУЕТСЯ (резерв под расширение, не разведено).
//
// На релейном блоке компрессор физически стоит сразу после четырёх
// насосов (позиция 5) — на карту Modbus это не влияет, но сбивает с
// толку при работе с самим железом.
// ------------------------------------------------------------
enum PumpChannel {
  pump1,
  pump2,
  pump3,
  pump4,
  // ПЛАНИРУЕТСЯ — резерв, физически не разведено.
  pump5(connected: false),
  pump6(connected: false),
  pump7(connected: false),
  pump8(connected: false);

  const PumpChannel({this.connected = true});

  final bool connected;

  // Встроенный Enum.index (0-based, порядок объявления) совпадает и с DO
  // (сам насос), и с DI (датчик уровня ЭТОГО ЖЕ насоса, см. sensorDI) —
  // это единственное место, где выражена связь "датчик уровня N относится
  // к насосу N": не таблица перекрёстных соответствий, а общий индекс.
  int get do_ => index;
  int get sensorDI => index;
  int get terminalNumber => index + 1; // 1-based номер клеммы на модуле
}


// ------------------------------------------------------------
// РЕЖИМ НАГРЕВА ТЭНа — решение 28.09.2026 (задача "контроль цикла по
// электросчётчику, температурный режим, готовность оплаты"): цель прогрева
// снижена с прежних 225°C до 190°C, во время обработки поддержание
// гистерезисом 170-190°C. preheatTargetC и maintainHighC сознательно
// равны одному и тому же числу (190) — это одна и та же физическая
// граница "ТЭН прогрет", а не совпадение, которое надо держать
// синхронизированным вручную.
// ------------------------------------------------------------
class HeaterThresholds {
  HeaterThresholds._();

  static const double preheatTargetC = 190.0; // preparing.dart — старт цикла
  static const double maintainLowC = 170.0; // treating.dart — гистерезис, ТЭН ВКЛ
  static const double maintainHighC = 190.0; // treating.dart — гистерезис, ТЭН ВЫКЛ

  // Решение оператора 28.09.2026: изначальные 10 секунд оказались опасны —
  // при полосе в 20 градусов дребезг реле физически невозможен (испаритель
  // не остывает/не греется на 20° за секунду), а вот блокировка нагрева,
  // пока температура продолжает падать, реальный риск для качества
  // обработки. 2-3 секунды защищают только от шума термопары (который
  // правильнее лечить усреднением показаний, а не блокировкой — усреднение
  // сюда пока не добавлено).
  //
  // ПОДТВЕРЖДЕНО замером 29.09.2026 (фаза 1, задача "контроль цикла по
  // электросчётчику"): естественное остывание испарителя 190°C→170°C без
  // обдува заняло 10 мин 58 с. При таком темпе (20° примерно за 11 минут)
  // дребезг реле на любом разумном интервале паузы физически исключён —
  // 3 секунды избыточно консервативны, но безопасны, менять не нужно.
  static const Duration maintainMinToggleInterval = Duration(seconds: 3);

  // Жёсткий пол: ниже этой температуры пауза выше не действует вообще —
  // качество обработки важнее ресурса реле. Взято по прикидке оператора
  // ("скажем 160"), число как таковое замером не уточнялось (при
  // измеренном темпе остывания ~11 мин/20° оно и не критично — пауза уже
  // не может вызвать дребезг ни выше, ни ниже пола), но подтверждено, что
  // условия для дребезга реле нет нигде в рабочем диапазоне.
  static const double maintainHardFloorC = 160.0;

  // Аварийный потолок температуры ТЭНа — единственное место порога: и
  // прогрев (preparing.dart), и обработка (treating.dart) берут его
  // отсюда (раньше число стояло в preparing.dart, а в обработке порога не
  // было вовсе). Ниже термовыключателя шкафа 260–280°C. Тексты ошибки
  // (error.dart) называют это же число.
  static const double overheatAbortC = 240.0;

  // ----------------------------------------------------------------
  // ДЕТЕКТОРЫ ОТКАЗА ДАТЧИКА ТЕМПЕРАТУРЫ И "УБЕГАЮЩЕГО" НАГРЕВА
  // (задача "детектор отказа датчика температуры", 2026-10-01).
  // Работают, пока ТЭН включён (прогрев и обработка), независимо от
  // показаний термопары как единственного источника истины: застывший
  // датчик при рабочем реле раньше грел воздух без обратной связи до
  // таймаута прогрева. Проверка нагрева по счётчику (800 Вт за 3 с) этого
  // не ловит — она проверяет ток, а не реакцию температуры.
  // Любое срабатывание = ОДНО подтверждённое событие → вывод из
  // обслуживания (OutOfServiceCode.tempSensorFault); подтип — в details.
  // ----------------------------------------------------------------

  // Нижняя граница: служебное значение обрыва термопары (HLS-KWL-4TC
  // физически отдаёт ~-500°C как "нет датчика", см. комментарий в
  // preparing.dart) заведомо ниже. ПОДТВЕРЖДЕНО (значение уже работало в
  // preparing.dart как _sensorFaultThreshold).
  static const double sensorPlausibleMinC = -100.0;

  // Верхняя граница: выше физика аппарата не пускает (термовыключатель
  // шкафа 260–280°C, существующий порог перегрева 240°C — см.
  // preparing.dart). НЕ ИЗМЕРЕНО, подлежит пересмотру — консервативно с
  // большим запасом над реальным диапазоном 18–210°C из замеров 29.09/01.10.
  static const double sensorPlausibleMaxC = 400.0;

  // Сколько плохих чтений подряд (null/ошибка шины/вне диапазона) считать
  // отказом, а не одиночным сбоем шины. Тик опроса 3 с → 9 с без единого
  // годного показания при включённом ТЭНе. Одиночный сбой чтения (шину
  // дёрнуло) сюда не попадает. НЕ ИЗМЕРЕНО, подлежит пересмотру.
  static const int sensorBadReadConfirmCount = 3;

  // Застывшее показание: при НЕПРЕРЫВНО включённом ТЭНе значение не
  // менялось (разница меньше sensorChangeEpsilonC) дольше этого окна.
  // ПОДТВЕРЖДЕНО частично: в логах фазы 1 (29.09) при включённом ТЭНе
  // соседние отсчёты с шагом 2 с НИ РАЗУ не совпадали (рост 1–3°C/с).
  // 9 с = три шага опроса с запасом. Режим с жидкостью (плато кипения) не
  // измерялся — НЕ ИЗМЕРЕНО, подлежит пересмотру после выездных испытаний.
  static const Duration sensorStaleWindow = Duration(seconds: 9);
  static const double sensorChangeEpsilonC = 0.05;

  // Нет роста при нагреве: после команды на ТЭН (и успешной проверки
  // 800 Вт) температура обязана вырасти не менее чем на noRiseMinC за
  // noRiseWindow. ПОДТВЕРЖДЕНО замером 29.09.2026: нагрев ≈2,2°C/с с ~20°C
  // (+17°C за 7 с с учётом лага термопары), с горячего старта ≥1°C/с —
  // за 12 с ожидается +12…+25°C, порог 3°C даёт 4–8-кратный запас.
  // Только в прогреве (сухой цикл, без жидкости): в режиме обработки с
  // жидкостью поведение не измерено.
  static const Duration noRiseWindow = Duration(seconds: 12);
  static const double noRiseMinC = 3.0;

  // Энергетический бюджет прогрева, Вт·ч, накопленных счётчиком с
  // момента команды на ТЭН до достижения цели по показаниям. Замеры:
  // 42 с (30.09, ≈17 Вт·ч) и 69 с (01.10, ≈28 Вт·ч) при ≈1,45 кВт — худший
  // измеренный нормальный прогрев ≈28 Вт·ч. Таймаут прогрева 180 с
  // набежал бы на ≈72 Вт·ч (preheatTimeout ниже). 45 Вт·ч — 1,6×
  // худшего нормального и ≈63% от энергии за 180 с (геометрическая
  // середина между ними): зимний холодный старт с запасом, но убегающий
  // нагрев обрывается задолго до таймаута. НЕ ПОДТВЕРЖДЕНО на холодном
  // аппарате (зима/улица) — пересмотреть по тесту нормального цикла,
  // записать запас в процентах.
  static const double preheatEnergyBudgetWh = 45.0;

  // Таймаут прогрева — последний рубеж, если ни один детектор не сработал
  // (например, мощность упала из-за просадки сети или частичного отказа
  // спирали: энергия копится медленнее бюджета, ограничивает только
  // время). Решение оператора 01.10.2026: 180 с (в коде стояло 600 с,
  // происхождение неизвестно — поднимать только по замеру холодного
  // старта). Худший замеренный нормальный прогрев ≈77 с на полной
  // мощности (≈28 Вт·ч) — двукратный запас с лишним. Срабатывание
  // выводит аппарат из обслуживания (OutOfServiceCode.heatTimeout).
  static const Duration preheatTimeout = Duration(seconds: 180);

  // Пробный цикл (сервисное меню, без оплаты): максимальная длительность
  // и допустимая начальная температура (горячий испаритель — ждать).
  static const Duration trialMaxDuration = Duration(seconds: 30);
  static const double trialMaxStartTempC = preheatTargetC;
}


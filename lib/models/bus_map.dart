// Используется для распознавания сбоя нагрева/насоса по показаниям
// счётчика без доп. датчиков (фаза 2) — три уровня чётко разделены и
// складываются линейно при одновременной работе (компрессор+насос
// проверено: 48+38≈76 Вт при совместном включении).
// ------------------------------------------------------------
class PowerSignature {
  PowerSignature._();

  static const double idleW = 15.4; // холостой ход (плата, реле обесточены)
  static const double compressorDeltaW = 33.0; // компрессор сверх холостого
  static const double pumpDeltaW = 25.0; // один насос сверх холостого
  static const double heaterW = 1430.0; // ТЭН испарителя (не 2 кВт, как считалось)
  static const double heatingRateCPerS = 2.2; // средний нагрев от ~20°C
  static const Duration coolingTime190to170 = Duration(minutes: 10, seconds: 58);

  // Согласованный порог просадки сети — ниже него мощность ТЭНа заметно
  // падает (P ~ V², 227→242 В уже даёт разницу ~200 Вт), цикл растягивается.
  // Не авария, только предупреждение в журнал (фаза 2, часть 3).
  static const double gridVoltageSagWarningV = 220.0;
}

// ------------------------------------------------------------
// ПРОВЕРКА НАГРЕВА ПО СЧЁТЧИКУ — фаза 2, часть 1.
//
// Обоснование порога: ТЭН даёт ~1430 Вт (PowerSignature.heaterW), всё
// остальное в аппарате вместе взятое — меньше 80 Вт (компрессор+насос
// ≈76 Вт максимум). 800 Вт лежит посередине с огромным запасом в обе
// стороны — ложные срабатывания в любую сторону исключены. Отклик
// счётчика меньше секунды (подтверждено фазой 1), 3 секунды дают
// трёхкратный запас на это же измерение.
// ------------------------------------------------------------
class HeaterVerification {
  HeaterVerification._();

  static const double thresholdW = 800.0;
  static const Duration window = Duration(seconds: 3);
  // Интервал опроса счётчика внутри окна проверки — не 1 замер на все 3
  // секунды: несколько отсчётов дают запас на случай, если один опрос
  // не успеет (см. также CycleEnergyService, который ведёт тот же учёт
  // для всего остального цикла раз в секунду).
  static const Duration pollInterval = Duration(milliseconds: 500);
}

// ------------------------------------------------------------
// МОНЕТОПРИЁМНИК — калибровка импульсов.
//
// ВАЖНО: монетоприёмник физически заменён 2026-08-21 (см.
// docs/coin_acceptor.md) — значения ниже соответствуют ТЕКУЩЕМУ
// физическому устройству, проверены на 4 подряд брошенных монетах.
// Старая калибровка (2 импульса → 1€, 4 импульса → 2€) относилась к
// демонтированному прежнему приёмнику и БОЛЬШЕ НЕ АКТУАЛЬНА — если
// где-то в документации или задании встретятся эти старые цифры, верны
// не они, а таблица здесь.
// ------------------------------------------------------------
class CoinAcceptorCalibration {
  CoinAcceptorCalibration._();

  // Импульс = переход DI8 false→true. 1 импульс → 1€, 2 и более → 2€.
  static const int pulsesFor1Euro = 1;
  static const int centsFor1Pulse = 100;
  static const int centsFor2PlusPulses = 200;

  // Опрос DI8 — интервал между чтениями и таймаут одного чтения.
  static const Duration pollInterval = Duration(milliseconds: 80);
  static const int pollTimeoutMs = 150;

  // Пауза между импульсами ВНУТРИ одной монеты, после которой серия
  // считается завершённой и номинал определяется по числу импульсов.
  // Подобрано по факту 21.08.2026: реальные паузы у этого приёмника
  // доходили до ~430 мс, более короткий порог (пробовали 350 мс) рвал
  // одну монету на несколько ложных серий.
  static const Duration coinSeriesGap = Duration(milliseconds: 600);
}

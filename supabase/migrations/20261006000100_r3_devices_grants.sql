-- ============================================================
-- R3: права на новые столбцы devices для панели.
-- Применять ПОСЛЕ 20261006000000_r3_rollouts.sql (там добавлены столбцы
-- devices.ring и devices.timezone). НЕ ПРИМЕНЕНО автоматически; SQL в
-- Supabase выполняет только владелец.
--
-- Почему нужен отдельный grant. На таблице devices права для authenticated
-- выданы ПО СТОЛБЦАМ, а не на всю таблицу: столбец token (секрет устройства)
-- для чтения закрыт намеренно — вошедший в панель пользователь не должен
-- видеть токены. Поэтому новый столбец автоматически читаемым НЕ становится:
-- без явного grant панель (и представление rollout_progress, которое
-- security_invoker и читает devices правами пользователя) не увидит
-- ring/timezone.
--
-- ВАЖНО: здесь выдаётся ТОЛЬКО select и ТОЛЬКО на эти два столбца. Токен и
-- прочие закрытые столбцы не трогаем. Запись ring/timezone идёт только через
-- функцию device_set_ring_tz (security definer), прямого update нет.
-- ============================================================

grant select (ring, timezone) on public.devices to authenticated;


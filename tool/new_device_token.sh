#!/usr/bin/env bash
# Перевыпуск токена ОДНОГО аппарата (потеря токена, подозрение на утечку).
#
#   tool/new_device_token.sh <ID>
#
# Что делает: генерирует новый токен (32 случайных байта, base64url без «=»,
# 43 знака), считает sha256 в hex и печатает на экран токен и готовый SQL
# с ХЕШЕМ. Ничего не пишет в файлы и ничего не отправляет в сеть.
#
# Дальше владелец: выполняет SQL в Supabase SQL Editor и вводит токен на
# планшете (сервисное меню → облако) либо пишет новый файл конфигурации.
# Токен не сохранять, не пересылать и не вставлять в чат: в базе только хеш,
# восстановить токен по нему нельзя.
#
# Новый аппарат заводится генератором tool/provision_devices.py (он же
# выдаёт код привязки); этот скрипт — только для уже заведённого номера.
set -euo pipefail

ID="${1:-}"

die() { echo "ОШИБКА: $*" >&2; exit 1; }

[ -n "$ID" ] || die "использование: tool/new_device_token.sh <ID>"
# тот же формат номера, что в генераторе (ID_RE): SQL собирается без экранирования
printf '%s' "$ID" | grep -Eq '^[A-Za-z0-9._-]{1,64}$' \
  || die "недопустимый номер аппарата (буквы, цифры, . _ -, до 64)"

command -v openssl >/dev/null 2>&1 || die "не найдена утилита openssl"
if command -v shasum >/dev/null 2>&1; then
  sha256() { shasum -a 256 | cut -d' ' -f1; }
elif command -v sha256sum >/dev/null 2>&1; then
  sha256() { sha256sum | cut -d' ' -f1; }
else
  die "не найдена утилита shasum или sha256sum"
fi

TOKEN="$(openssl rand -base64 32 | tr '+/' '-_' | tr -d '=\n')"
[ "${#TOKEN}" -eq 43 ] || die "токен неожиданной длины"
HASH="$(printf '%s' "$TOKEN" | sha256)"
printf '%s' "$HASH" | grep -Eq '^[0-9a-f]{64}$' || die "хеш неожиданного вида"

cat <<EOF
Аппарат: $ID

Новый токен (ввести на планшете; не сохранять и не пересылать):
$TOKEN

SQL для Supabase SQL Editor (в базу пишется только хеш):
update public.devices set token_hash = '$HASH' where id = '$ID';

После выполнения SQL аппарат со старым токеном получает отказ auth, пока на нём
не введён новый токен.
EOF
